from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


def export_comparison_pdf(comparison_result, filename="change_record.pdf"):

    doc = SimpleDocTemplate(
        filename,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        spaceAfter=8,
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        spaceBefore=12,
        spaceAfter=6,
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["BodyText"],
        leading=14,
        spaceAfter=4,
        wordWrap="CJK",
    )

    story = []

    story.append(Paragraph("GraphWorX Change Record", title_style))
    story.append(
        Paragraph(
            "Comparison report generated by GDFX Version Control",
            styles["Normal"],
        )
    )
    story.append(Spacer(1, 10))

    sections = [
        ("Added Objects", comparison_result.added, colors.green),
        ("Removed Objects", comparison_result.removed, colors.red),
    ]

    for heading, objects, color in sections:
        story.append(
            Paragraph(
                f'<font color="{color.hexval()}">'
                f'{escape(heading)}</font>',
                heading_style,
            )
        )

        if not objects:
            story.append(Paragraph("None", body_style))
        else:
            for obj in objects:
                story.append(
                    Paragraph(
                        escape(f"{obj}"),
                        body_style,
                    )
                )

    # Modified Objects
    story.append(
        Paragraph(
            f'<font color="{colors.darkgoldenrod.hexval()}">'
            'Modified Objects</font>',
            heading_style,
        )
    )

    modified_found = False

    for pair in comparison_result.pairs:
        if pair.is_matched() and pair.match_result.differences:
            modified_found = True

            story.append(
                Paragraph(
                    f"<b>{escape(str(pair.old_object.object_id))}</b>",
                    body_style,
                )
            )

            for difference in pair.match_result.differences:
                story.append(
                    Paragraph(
                        escape(f"  {difference}"),
                        body_style,
                    )
                )

    if not modified_found:
        story.append(Paragraph("None", body_style))

    # Footer on every page
    def add_page_number(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 9)
        canvas.setFillColor(colors.grey)
        canvas.drawCentredString(
            A4[0] / 2,
            10 * mm,
            f"Page {document.page}",
        )
        canvas.restoreState()

    doc.build(
        story,
        onFirstPage=add_page_number,
        onLaterPages=add_page_number,
    )

    print(f"PDF exported successfully: {filename}")
